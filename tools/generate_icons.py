"""Export the selected SVG into web/Android assets. Does not build an APK.

    python -m pip install -r tools/icon-requirements.txt
    python tools/generate_icons.py --variant 01-vortex
"""
from argparse import ArgumentParser
from io import BytesIO
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw, ImageFont
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
BRAND = ROOT / "assets/branding"
RES = ROOT / "android/app/src/main/res"
PUBLIC = ROOT / "public"
NS = "http://www.w3.org/2000/svg"
BG, FG = "#0B0E14", "#EDF3FA"
DENSITIES = {"ldpi": .75, "mdpi": 1, "hdpi": 1.5,
             "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def render(svg, size):
    return Image.open(BytesIO(resvg_py.svg_to_bytes(
        svg_string=svg, width=size, height=size,
        skip_system_fonts=True))).convert("RGBA")


def vector(path, foreground=False, monochrome=False):
    # 108dp adaptive layers are cropped to 72dp by the launcher. Keep the whole
    # symbol inside the central 66dp safe circle, including its pointed tips.
    viewport = 108 if foreground else 100
    group = ' android:scaleX="0.66" android:scaleY="0.66" android:translateX="21" android:translateY="21"'
    background = '' if foreground or monochrome else f'<path android:fillColor="{BG}" android:pathData="M0 0H100V100H0Z"/>'
    art = f'<path android:fillColor="{"#FFFFFF" if monochrome else FG}" android:pathData="{path}"/>'
    if foreground:
        art = f'<group{group}>{art}</group>'
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py from assets/branding/icon.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="{viewport}dp" android:height="{viewport}dp" android:viewportWidth="{viewport}" android:viewportHeight="{viewport}">
{background}{art}
</vector>
'''


def adaptive(monochrome=False):
    mono = '\n    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>' if monochrome else ''
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/generate_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>{mono}
</adaptive-icon>
'''


def preview():
    variants = sorted((BRAND / "variants").glob("*.svg"))
    canvas = Image.new("RGB", (360 * len(variants), 590), "#141922")
    draw = ImageDraw.Draw(canvas)
    # DejaVuSans ships with Pillow on many systems; use Windows Segoe if present.
    font_path = Path("C:/Windows/Fonts/segoeui.ttf")
    font = ImageFont.truetype(str(font_path), 20) if font_path.exists() else ImageFont.load_default(size=20)
    small = ImageFont.truetype(str(font_path), 14) if font_path.exists() else ImageFont.load_default(size=14)
    for index, variant in enumerate(variants):
        svg = variant.read_text(encoding="utf-8")
        x = index * 360 + 20
        draw.text((x, 12), variant.stem, fill=FG, font=font)
        canvas.paste(render(svg, 320), (x, 48))
        render(svg, 512).save(variant.with_suffix(".png"))
        for column, size in enumerate((16, 24, 32, 48)):
            left = x + column * 80
            image = render(svg, size)
            canvas.paste(image, (left, 390))
            draw.text((left, 446), f"{size} px", fill="#A6AFBD", font=small)
            canvas.paste(image.resize((size * 2, size * 2), Image.Resampling.NEAREST), (left, 480))
    canvas.save(BRAND / "options.png")


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--variant", choices=("01-vortex", "02-orbit", "03-pulse"))
    args = parser.parse_args()
    if args.variant:
        shutil.copyfile(BRAND / "variants" / f"{args.variant}.svg", BRAND / "icon.svg")
    svg = (BRAND / "icon.svg").read_text(encoding="utf-8")
    tree = ET.fromstring(svg)
    paths = tree.findall(f"{{{NS}}}path")
    if len(paths) != 1 or paths[0].get("transform"):
        raise ValueError("The source must contain one untransformed filled path")
    path = paths[0].attrib["d"]
    mark = f'<svg xmlns="{NS}" viewBox="0 0 100 100"><path fill="{FG}" d="{path}"/></svg>\n'
    write(BRAND / "mark.svg", mark)
    # In-app artwork comes from the same source, tinted by the active UI theme.
    write(ROOT / "components/ui/CycloneMark.tsx", f'''// Generated by tools/generate_icons.py from assets/branding/icon.svg.
export const CycloneMark = ({{ className }}: {{ className?: string }}) => (
    <svg className={{className}} viewBox="0 0 100 100" aria-hidden="true">
        <path fill="currentColor" d="{path}" />
    </svg>
);
''')
    write(PUBLIC / "icon.svg", svg)
    icon = render(svg, 1024)
    icon.save(BRAND / "icon.png")
    icon.save(BRAND / "icon.ico", sizes=[(s, s) for s in ICO_SIZES])
    shutil.copyfile(BRAND / "icon.ico", PUBLIC / "favicon.ico")
    (PUBLIC / "icons").mkdir(exist_ok=True)
    for size in (16, 24, 32, 48, 64, 128, 180, 192, 256, 512):
        render(svg, size).save(PUBLIC / "icons" / f"icon-{size}.png")
    render(svg, 180).save(PUBLIC / "apple-touch-icon.png")
    render(svg, 512).save(ROOT / "fastlane/metadata/android/en-US/images/icon.png")

    write(RES / "drawable/cyclone_icon.xml", vector(path))
    for directory in ("drawable", "drawable-v24"):
        write(RES / directory / "ic_launcher_foreground.xml", vector(path, foreground=True))
    write(RES / "drawable/ic_launcher_monochrome.xml", vector(path, foreground=True, monochrome=True))
    write(RES / "drawable/ic_stat_cyclone.xml", vector(path, monochrome=True))
    write(RES / "values/ic_launcher_background.xml", f'<resources><color name="ic_launcher_background">{BG}</color></resources>\n')
    for version in (26, 33):
        for name in ("ic_launcher", "ic_launcher_round"):
            write(RES / f"mipmap-anydpi-v{version}" / f"{name}.xml", adaptive(version == 33))

    # Retain the old resource names and component aliases for existing installs.
    # Theme changes must never bring back the previous colored artwork.
    for directory in ("drawable", "drawable-night"):
        for palette in ("rose", "lavender", "sage", "ocean", "amber"):
            for mode in ("light", "dark"):
                write(RES / directory / f"cyclone_{palette}_{mode}.xml", vector(path))

    foreground = f'<svg xmlns="{NS}" viewBox="0 0 108 108"><g transform="translate(21 21) scale(.66)"><path fill="{FG}" d="{path}"/></g></svg>'
    for density, factor in DENSITIES.items():
        directory = RES / f"mipmap-{density}"
        directory.mkdir(exist_ok=True)
        size = round(48 * factor)
        render(svg, size).save(directory / "ic_launcher.png")
        rounded = render(svg, size * 4)
        mask = Image.new("L", rounded.size)
        ImageDraw.Draw(mask).ellipse((0, 0, rounded.width - 1, rounded.height - 1), fill=255)
        rounded.putalpha(mask)
        rounded.resize((size, size), Image.Resampling.LANCZOS).save(directory / "ic_launcher_round.png")
        layer_size = round(108 * factor)
        render(foreground, layer_size).save(directory / "ic_launcher_foreground.png")
        Image.new("RGB", (layer_size, layer_size), BG).save(directory / "ic_launcher_background.png")

    # Capacitor's pre-Android-12 splash images, for every orientation and theme.
    for splash in RES.glob("*/splash.png"):
        with Image.open(splash) as old:
            width, height = old.size
        factor = next((f for d, f in DENSITIES.items() if splash.parent.name.endswith("-" + d)), 1)
        size = min(round(144 * factor), min(width, height) // 2)
        image = Image.new("RGB", (width, height), BG)
        image.paste(render(svg, size), ((width - size) // 2, (height - size) // 2))
        image.save(splash)
    preview()
    print("Generated SVG, ICO, web PNGs, Android vectors, adaptive icons, legacy icons and splash images. No APK built.")


if __name__ == "__main__":
    main()
